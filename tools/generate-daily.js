#!/usr/bin/env node
/*
 * Builds src/levels-daily.js: the Daily Heist pool, 28 cases (4 weeks).
 * Each week runs easy on Monday to hard on Sunday. The game picks the case for today's date.
 * Uses the same layout makers and difficulty checks as the city cases (tools/generate-city.js).
 *   node tools/generate-daily.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { makeLevel, check, mulberry32 } = require('./generate-city.js');

// Monday (easy) to Sunday (hard).
const WEEK = [
  { district: 'oldTown', exits: 4, units: { block: 4, spike: 1, heli: 1 }, cars: 1, rank: 2 },
  { district: 'ringRoad', exits: 4, units: { block: 4, spike: 1, traffic: 1, heli: 1 }, cars: 1, rank: 3 },
  { district: 'riverside', exits: 4, units: { block: 4, spike: 1, heli: 1 }, cars: 2, rank: 2, crews: 2 },
  { district: 'oldTown', exits: 5, units: { block: 4, spike: 1, traffic: 1, heli: 1 }, cars: 2, rank: 3 },
  { district: 'ringRoad', exits: 5, units: { block: 4, spike: 2, traffic: 1, heli: 1 }, cars: 1, rank: 4 },
  { district: 'riverside', exits: 5, units: { block: 5, spike: 2, traffic: 1, heli: 1 }, cars: 2, rank: 3, crews: 2 },
  { district: 'ringRoad', exits: 5, units: { block: 5, spike: 2, traffic: 1, heli: 1 }, cars: 2, rank: 4, speed: 3 },
];
const NAMES = [
  'Armored Truck', 'Jewel Job', 'Payroll Grab', 'Casino Night', 'Museum Gala', 'Vault Thirteen', 'Diamond Run',
  'Coin Exchange', 'Gold Bars', 'Art Auction', 'Mint Condition', 'Night Deposit', 'Safe Cracker', 'Crown Jewels',
  'Pawn Shop', 'Bullion Van', 'Lottery Office', 'Stamp Collection', 'Penthouse Safe', 'Cash Machine', 'Big Score',
  'Ticket Office', 'Rare Coins', 'Gallery Opening', 'Watch Store', 'Treasury Annex', 'Wire Transfer', 'The Last Job',
];

function main() {
  const out = [];
  const t0 = Date.now();
  for (let k = 0; k < 28; k++) {
    const base = WEEK[k % 7];
    const spec = JSON.parse(JSON.stringify(base));
    spec.id = 100 + k; // >= 20: also has to beat the medium chief
    spec.units = Object.assign({ block: 0, spike: 0, traffic: 0, heli: 0 }, spec.units);
    spec.speed = spec.speed || 2;
    spec.parMin = 2; spec.parMax = 8;
    let rng = mulberry32(777001 + k * 7919);
    let found = null, tries = 0;
    const why = {};
    while (!found && tries < 480) {
      if (tries === 240) { rng = mulberry32(991003 + k * 104723); spec.units.block = base.units.block; } // second seed
      tries++;
      const lv = makeLevel(rng, spec);
      if (!lv) { why['no layout'] = (why['no layout'] || 0) + 1; continue; }
      const res = check(lv, spec);
      if (res.ok) { found = { lv, res }; break; }
      why[res.why] = (why[res.why] || 0) + 1;
      if (tries % 30 === 0) {
        const easy = (why['too easy'] || 0) + (why['par low'] || 0), hard = why['too hard'] || 0;
        if (easy > hard * 2 && spec.units.block > 2) spec.units.block--;
        else if (hard > easy * 2) spec.units.block++;
      }
    }
    if (!found) { console.log(`FAILED daily ${k + 1}: ${JSON.stringify(why)}`); continue; }
    const lv = Object.assign({ id: 1001 + k, daily: true, name: NAMES[k] }, found.lv, { par: found.res.par });
    lv.units = Object.assign({}, spec.units);
    out.push(lv);
    console.log(`daily ${String(k + 1).padStart(2)} ${NAMES[k].padEnd(17)} ${spec.district.padEnd(9)} par ${found.res.par}  rank ${spec.rank}  tries ${tries}`);
  }
  const body =
    '/* Daily Heist pool (28 cases, Monday easy to Sunday hard). Generated by tools/generate-daily.js. Do not edit by hand. */\n' +
    '(function (root) {\n' +
    '  const LEVELS = [\n' + out.map((l) => '    ' + JSON.stringify(l)).join(',\n') + '\n  ];\n' +
    "  if (typeof module === 'object' && module.exports) module.exports = LEVELS;\n" +
    '  else root.MG_LEVELS_DAILY = LEVELS;\n' +
    "})(typeof self !== 'undefined' ? self : this);\n";
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'levels-daily.js'), body);
  console.log(`\nWrote ${out.length} daily cases in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
}

main();
