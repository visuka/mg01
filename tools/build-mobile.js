#!/usr/bin/env node
/*
 * Packs the web game into one self-contained HTML page for the phone app (mobile/).
 *   node tools/build-mobile.js
 * Writes mobile/game/game-html.ts (imported by the app) and mobile/game/game.html (for a browser check).
 * Runs by itself before `npm start` in mobile/ and on Expo's build servers (eas-build-post-install).
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'mobile', 'game');

let page = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
let count = 0;
page = page.replace(/<script src="([^"]+)"><\/script>/g, (_, src) => {
  const code = fs.readFileSync(path.join(ROOT, src), 'utf8').replace(/<\/script/gi, '<\\/script');
  count++;
  return `<script>/* ${src} */\n${code}\n</script>`;
});
if (count === 0) throw new Error('No <script src> tags found in index.html');

// Same document skeleton the web build gets from the artifact host.
const html =
  '<!doctype html><html lang="en"><head><meta charset="utf-8">' +
  '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">' +
  '<style>body{margin:0}[hidden]{display:none!important}</style>' +
  '</head><body>' + page + '</body></html>';

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'game.html'), html);
fs.writeFileSync(
  path.join(OUT, 'game-html.ts'),
  '// Generated by tools/build-mobile.js from index.html and src/. Do not edit.\n' +
  `export const GAME_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`Packed ${count} scripts into mobile/game (${(html.length / 1024).toFixed(0)} KB)`);
